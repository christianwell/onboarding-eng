test('search confines keyboard focus and restores it on Escape and close', async ({ page }) => {
  await page.goto('/program/stardance/step/notifications')
  const trigger = page.locator('.search-trigger')
  await trigger.click()
  const dialog = page.getByRole('dialog', { name: 'Search messages, people, and channels' })
  const input = page.getByPlaceholder('Search messages, people, and channels')
  await expect(dialog).toBeVisible()
  await expect(input).toBeFocused()
  await input.press('Shift+Tab')
  await expect(dialog.getByRole('button', { name: 'Close search' })).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(input).toBeFocused()
  await input.fill('Christian')
  await input.press('ArrowDown')
  await input.press('Tab')
  await expect(dialog.getByRole('button', { name: 'Close search' })).toBeFocused()
  for (let index = 0; index < 12; index++) {
    await page.keyboard.press('Tab')
    await expect.poll(() => dialog.evaluate((element) => element.contains(document.activeElement))).toBe(true)
  }
  await page.keyboard.press('Escape')
  await expect(dialog).toHaveCount(0)
  await expect(trigger).toBeFocused()
  await trigger.click()
  await dialog.getByRole('button', { name: 'Close search' }).click()
  await expect(trigger).toBeFocused()
})
