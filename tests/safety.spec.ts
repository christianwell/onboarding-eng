import { expect, Page, test } from '@playwright/test'

async function openJan(page: Page) {
  await page.getByRole('button', { name: /Jan adultman/ }).click()
  await expect(page.locator('.messages')).toContainText("You're stinky and ugly!")
}

async function forwardToShroud(page: Page, note = '') {
  await expect.poll(() => page.getByRole('button', { name: 'Forward message', exact: true }).evaluate((button) => {
    const action = button.getBoundingClientRect()
    const message = button.closest('article')!.getBoundingClientRect()
    const body = button.closest('article')!.querySelector('.message-content > p')!.getBoundingClientRect()
    return action.left > message.left + message.width / 2 && action.top < body.top
  })).toBe(true)
  await page.getByRole('button', { name: 'Forward message', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Forward message', exact: true })
  await dialog.getByRole('textbox', { name: 'Forward to' }).fill('@shroud')
  await dialog.getByRole('button', { name: 'shroud APP', exact: true }).click()
  if (note) await dialog.getByRole('textbox', { name: 'Add a note' }).fill(note)
  await dialog.getByRole('button', { name: 'Forward', exact: true }).click()
  await expect(page.locator('.channel-header h2')).toHaveText('shroud')
  await expect(page.locator('.messages .forwarded-message')).toContainText('Jan adultman')
  await expect(page.locator('.messages .forwarded-message')).toContainText("You're stinky and ugly!")
  await expect(page.locator('.completion-modal')).toHaveCount(0)
  await page.getByRole('button', { name: '1 reply View thread' }).click()
}

for (const withUsername of [false, true]) {
  test(`forwarding the original DM completes only on Submit (${withUsername ? 'named' : 'anonymous'})`, async ({ page }) => {
    await page.goto('/step/safety')
    await openJan(page)
    const note = withUsername ? 'This happened in my DMs.' : ''
    await forwardToShroud(page, note)
    if (note) await expect(page.locator('.thread-panel')).toContainText(note)
    await expect(page.locator('.thread-panel .forwarded-message')).toContainText("You're stinky and ugly!")
    const identity = page.getByRole('checkbox', { name: 'Include my username' })
    await expect(identity).not.toBeChecked()
    if (withUsername) await identity.check()
    await expect(page.locator('.completion-modal')).toHaveCount(0)
    await page.getByRole('button', { name: 'Submit', exact: true }).click()
    await expect(page.locator('.completion-modal')).toBeVisible()
  })
}

test('dismissal, invalid recipients, and Cancel leave forwarding unfinished', async ({ page }) => {
  await page.goto('/step/safety')
  await openJan(page)
  const trigger = page.getByRole('button', { name: 'Forward message', exact: true })
  const dialog = page.getByRole('dialog', { name: 'Forward message', exact: true })
  await trigger.click()
  await expect(dialog.getByRole('textbox', { name: 'Forward to' })).toBeFocused()
  await expect(dialog.getByRole('button', { name: 'Forward', exact: true })).toBeDisabled()
  await dialog.getByRole('textbox', { name: 'Forward to' }).fill('@Nova')
  await expect(dialog.getByRole('button', { name: 'shroud APP', exact: true })).toHaveCount(0)
  await expect(dialog.getByRole('button', { name: 'Forward', exact: true })).toBeDisabled()
  await page.keyboard.press('Escape')
  await expect(dialog).toHaveCount(0)
  await expect(trigger).toBeFocused()
  await trigger.click()
  await dialog.getByRole('button', { name: 'Close forward message' }).click()
  await trigger.click()
  await page.locator('.forward-backdrop').click({ position: { x: 5, y: 5 } })
  await trigger.click()
  await expect(dialog.getByRole('heading', { name: 'Forward this message' })).toBeVisible()
  await dialog.getByPlaceholder('Search for channel or person').fill('sh')
  await dialog.getByRole('button', { name: 'shroud APP', exact: true }).click()
  await expect(dialog.getByRole('textbox', { name: 'Add a note' })).toBeFocused()
  await page.keyboard.press('Tab')
  await page.keyboard.press('Tab')
  await expect(dialog.getByRole('button', { name: 'Forward', exact: true })).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(dialog.getByRole('link', { name: 'Read the Hack Club Code of Conduct ↗' })).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(dialog.getByRole('button', { name: 'Close forward message' })).toBeFocused()
  await page.keyboard.press('Shift+Tab')
  await expect(dialog.getByRole('link', { name: 'Read the Hack Club Code of Conduct ↗' })).toBeFocused()
  await page.keyboard.press('Shift+Tab')
  await expect(dialog.getByRole('button', { name: 'Forward', exact: true })).toBeFocused()
  await dialog.getByRole('button', { name: 'Remove shroud', exact: true }).click()
  await expect(dialog.getByRole('textbox', { name: 'Forward to' })).toBeFocused()
  await expect(dialog.getByRole('textbox', { name: 'Forward to' })).toHaveValue('')
  await expect(dialog.getByRole('button', { name: 'Forward', exact: true })).toBeDisabled()
  await dialog.getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(page.locator('.channel-header h2')).toHaveText('Jan adultman')
  await expect(page.locator('.completion-modal')).toHaveCount(0)
  await expect(page.locator('.messages .forwarded-message')).toHaveCount(0)
})

for (const reducedMotion of ['no-preference', 'reduce'] as const) {
  for (const narrow of [false, true]) {
    test(`forwarding keeps step guidance and targets the next action (${reducedMotion}, ${narrow ? 'narrow' : 'desktop'})`, async ({ page }) => {
      await page.emulateMedia({ reducedMotion })
      if (narrow) await page.setViewportSize({ width: 340, height: 510 })
      await page.goto(`/program/${narrow ? 'stardance' : 'slack'}/step/safety`)
      if (narrow) await page.getByRole('button', { name: 'Open channel list' }).click()
      await openJan(page)
      await page.getByRole('button', { name: 'Forward message', exact: true }).click()
      const dialog = page.getByRole('dialog', { name: 'Forward message', exact: true })
      const guide = dialog.getByRole('region', { name: /onboarding guide/ })
      await expect(guide).toBeVisible()
      await expect(guide.locator('.guide-step')).toHaveAttribute('aria-label', 'Step 1 of 2')
      await expect(guide.locator('.task-box')).toHaveText('YOUR TASKForward this message to @shroud.')
      await expect.poll(() => guide.locator('.task-box').evaluate((task) => {
        const rect = task.getBoundingClientRect()
        const card = task.closest('.coach')!.getBoundingClientRect()
        return rect.top >= card.top && rect.bottom <= card.bottom && card.top >= 0 && card.bottom <= innerHeight
      })).toBe(true)
      const target = dialog.locator('.forward-target')
      await expect(target).toHaveClass(/forward-to/)
      const pulse = () => target.evaluate((element) => getComputedStyle(element, '::after').boxShadow)
      if (reducedMotion === 'no-preference') {
        const initial = await pulse()
        await expect.poll(pulse).not.toBe(initial)
      } else {
        await expect.poll(() => target.evaluate((element) => parseFloat(getComputedStyle(element, '::after').animationDuration))).toBeLessThan(0.001)
      }
      await dialog.getByRole('textbox', { name: 'Forward to' }).fill('@nobody')
      await expect(target).toHaveClass(/forward-to/)
      await dialog.getByRole('textbox', { name: 'Forward to' }).fill('@shroud')
      await expect(target).toHaveAccessibleName('shroud APP')
      await dialog.getByRole('button', { name: 'shroud APP', exact: true }).click()
      await expect(target).toHaveAccessibleName('Forward')
      await expect(guide).toBeVisible()
      await dialog.getByRole('button', { name: 'Remove shroud', exact: true }).click()
      await expect(target).toHaveClass(/forward-to/)
      await dialog.getByRole('textbox', { name: 'Forward to' }).fill('shroud')
      await dialog.getByRole('button', { name: 'shroud APP', exact: true }).click()
      await dialog.getByRole('button', { name: 'Forward', exact: true }).click()
      await expect(dialog).toHaveCount(0)
      await expect(page.getByRole('heading', { name: 'Anonymous, or with your name on it?', exact: false })).toBeVisible()
      await expect(page.locator('.completion-modal')).toHaveCount(0)
      await page.getByRole('button', { name: '1 reply View thread' }).click()
      await page.getByRole('button', { name: 'Submit', exact: true }).click()
      await expect(page.locator('.completion-modal')).toBeVisible()
    })
  }
}

test('Shroud Cancel allows retry, switching conversations preserves the pending report, and reload starts fresh', async ({ page }) => {
  await page.goto('/step/safety')
  await openJan(page)
  await forwardToShroud(page, 'First attempt')
  await page.getByRole('checkbox', { name: 'Include my username' }).check()
  await page.getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(page.locator('.shroud-prompt')).toContainText('This report has been cancelled.')
  await expect(page.locator('.completion-modal')).toHaveCount(0)
  await page.getByRole('button', { name: 'Close thread' }).click()
  await openJan(page)
  await forwardToShroud(page)
  await expect(page.getByRole('checkbox', { name: 'Include my username' })).not.toBeChecked()
  await page.getByRole('button', { name: 'Close thread' }).click()
  await openJan(page)
  await page.getByRole('button', { name: 'Search Hack Club', exact: true }).click()
  await page.getByPlaceholder('Search messages, people, and channels').fill('@shroud')
  await page.getByRole('button', { name: 'Open DM with shroud' }).click()
  await page.getByRole('button', { name: '1 reply View thread' }).click()
  await expect(page.getByRole('button', { name: 'Submit', exact: true })).toBeVisible()
  await expect(page.locator('.thread-panel .forwarded-message')).toContainText('Jan adultman')
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Oh, looks like you got a DM!', exact: false })).toBeVisible()
  await expect(page.locator('.completion-modal')).toHaveCount(0)
  await openJan(page)
  await expect(page.getByRole('button', { name: 'Forward message', exact: true })).toBeVisible()
})

for (const program of ['slack', 'stardance']) {
  test(`${program} keeps the surrounding lessons and advances only after Submit`, async ({ page }) => {
    await page.route(`**/programs/${program}/config.yaml`, async (route) => {
      const response = await route.fetch()
      const yaml = (await response.text()).replace(/  lessons:\n(?:    - [^\n]+\n)+/, '  lessons:\n    - channels\n    - safety\n    - notifications\n')
      await route.fulfill({ response, body: yaml })
    })
    await page.goto(`/program/${program}`)
    await page.getByRole('button', { name: 'Let’s get started' }).click()
    await page.locator('.channel-list').getByRole('button', { name: program === 'slack' ? 'slack-guide' : 'stardance', exact: true }).click()
    await openJan(page)
    await forwardToShroud(page)
    await expect(page.getByRole('heading', { name: 'Anonymous, or with your name on it?', exact: false })).toBeVisible()
    await page.getByRole('button', { name: 'Submit', exact: true }).click()
    await expect(page.getByRole('heading', { name: 'Make notifications work for you', exact: false })).toBeVisible()
    await expect(page.locator('.completion-modal')).toHaveCount(0)
  })
}

